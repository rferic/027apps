import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { SUPPORTED_LOCALES, type TranslationMap } from "./types.js";
import { scanSources } from "./scan.js";

export interface CheckResult {
  success: boolean;
  errors: string[];
  warnings: string[];
}

const ok = (): CheckResult => ({ success: true, errors: [], warnings: [] });

/** `{name}` style placeholders in a string. */
export function extractPlaceholders(text: string): Set<string> {
  const placeholders = new Set<string>();
  for (const match of text.matchAll(/\{([^{}]+)\}/g)) {
    if (match[1]) placeholders.add(match[1]);
  }
  return placeholders;
}

/** Every locale must have exactly the catalog keys (English is the catalog). */
export function checkLocales(
  catalog: readonly string[],
  locales: Record<string, TranslationMap>,
): CheckResult {
  const result = ok();
  const catalogSet = new Set(catalog);

  for (const locale of SUPPORTED_LOCALES) {
    if (locale === "en") continue;
    const map = locales[locale];
    if (!map) {
      result.success = false;
      result.errors.push(`${locale}: missing locale file`);
      continue;
    }
    const keys = new Set(Object.keys(map));
    const missing = catalog.filter((key) => !keys.has(key));
    const extra = [...keys].filter((key) => !catalogSet.has(key));
    if (missing.length > 0) {
      result.success = false;
      result.errors.push(`${locale}: missing ${missing.length} key(s): ${missing.slice(0, 3).join(" | ")}`);
    }
    if (extra.length > 0) {
      result.success = false;
      result.errors.push(`${locale}: extra ${extra.length} key(s): ${extra.slice(0, 3).join(" | ")}`);
    }
  }
  return result;
}

/** Placeholders must match between the English text and each translation. */
export function checkPlaceholders(
  catalog: readonly string[],
  locales: Record<string, TranslationMap>,
): CheckResult {
  const result = ok();

  for (const locale of SUPPORTED_LOCALES) {
    if (locale === "en") continue;
    const map = locales[locale];
    if (!map) continue;

    for (const textEn of catalog) {
      const translated = map[textEn];
      if (translated === undefined) continue;
      const expected = extractPlaceholders(textEn);
      const actual = extractPlaceholders(translated);
      const missing = [...expected].filter((name) => !actual.has(name));
      const extra = [...actual].filter((name) => !expected.has(name));
      if (missing.length > 0 || extra.length > 0) {
        result.success = false;
        result.errors.push(
          `${locale}: placeholder mismatch in "${textEn.slice(0, 40)}" (missing: ${missing.join(", ") || "-"}; extra: ${extra.join(", ") || "-"})`,
        );
      }
    }
  }
  return result;
}

/**
 * Catalog ↔ code. A `t("…")` string that is not in the catalog is an error (the
 * catalog is generated by `i18n:scan`). Catalog strings not used yet are a
 * warning: the login/setup texts are pre-seeded and adopted progressively.
 */
export function checkStaleness(catalog: readonly string[], codeStrings: readonly string[]): CheckResult {
  const result = ok();
  const catalogSet = new Set(catalog);
  const codeSet = new Set(codeStrings);

  const missing = codeStrings.filter((text) => !catalogSet.has(text));
  if (missing.length > 0) {
    result.success = false;
    result.errors.push(`${missing.length} string(s) used in code but missing from the catalog: ${missing.slice(0, 3).join(" | ")}`);
  }

  const unused = catalog.filter((text) => !codeSet.has(text));
  if (unused.length > 0) {
    result.warnings.push(`${unused.length} catalog string(s) are not wrapped in t() yet (UI adoption pending)`);
  }
  return result;
}

/** Runs every check and merges the results. */
export function runCheck(input: {
  catalog: readonly string[];
  locales: Record<string, TranslationMap>;
  codeStrings: readonly string[];
}): CheckResult {
  const result = ok();
  for (const partial of [
    checkLocales(input.catalog, input.locales),
    checkPlaceholders(input.catalog, input.locales),
    checkStaleness(input.catalog, input.codeStrings),
  ]) {
    result.success = result.success && partial.success;
    result.errors.push(...partial.errors);
    result.warnings.push(...partial.warnings);
  }
  return result;
}

function loadJson<T>(file: string): T {
  return JSON.parse(fs.readFileSync(file, "utf8")) as T;
}

function main(): void {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
  const catalogPath = path.join(repoRoot, "packages/i18n/catalog.en.json");
  const localesDir = path.join(repoRoot, "packages/i18n/locales");

  const catalog = loadJson<string[]>(catalogPath);
  const locales: Record<string, TranslationMap> = {};
  for (const locale of SUPPORTED_LOCALES) {
    if (locale === "en") continue;
    locales[locale] = loadJson<TranslationMap>(path.join(localesDir, `${locale}.json`));
  }
  const codeStrings = scanSources(path.join(repoRoot, "apps/admin/src"));

  const result = runCheck({ catalog, locales, codeStrings });
  for (const warning of result.warnings) process.stdout.write(`warning: ${warning}\n`);
  for (const error of result.errors) process.stderr.write(`error: ${error}\n`);

  if (!result.success) {
    process.stderr.write("i18n check failed.\n");
    process.exit(1);
  }
  process.stdout.write(`i18n check OK (${catalog.length} strings, ${SUPPORTED_LOCALES.length} locales).\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
